"""Emit the P-256 test vectors as Swift string literals.

Usage: python3 -I vectors.py CRYPTOKIT_SOURCE REVISION > vectors.swift

The Wycheproof (Apache-2.0) and CAVS files are read from the swift-crypto clone at the
pinned revision with `git show`, so nothing is vendored. Each vector becomes one line of
space-separated fields; an empty field is written as "-". p256.swift parses the lines.
"""
import json
import subprocess
import sys

source, revision = sys.argv[1], sys.argv[2]


def show(name):
    return subprocess.run(["git", "-C", source, "show", f"{revision}:Tests/Test Vectors/{name}"],
                          check=True, capture_output=True, text=True).stdout


def field(value):
    return value if value else "-"


def emit(name, rows):
    print(f"let {name} = \"\"\"")
    for row in rows:
        print(" ".join(field(v) for v in row))
    print("\"\"\"")


def ecdsa(name):
    rows = []
    for group in json.loads(show(name))["testGroups"]:
        key = group["publicKey"]["uncompressed"]
        for test in group["tests"]:
            rows.append((str(test["tcId"]), key, test["msg"], test["sig"], test["result"]))
    return rows


def ecdh(name, point_flag):
    rows = []
    for group in json.loads(show(name))["testGroups"]:
        for test in group["tests"]:
            compressed = "compressed" if point_flag and "CompressedPoint" in test["flags"] else "x963"
            rows.append((str(test["tcId"]), compressed, test["public"], test["private"],
                         test["shared"], test["result"]))
    return rows


def x963():
    rows, section, current = [], None, {}
    for line in show("ansx963_2001_sha256.txt").splitlines():
        line = line.strip()
        if line.startswith("[SHA-"):
            section = line
            continue
        key, sep, value = line.partition("=")
        if section != "[SHA-256]" or not sep:
            continue
        key, value = key.strip(), value.strip()
        if key == "Z":
            current = {"Z": value}
        elif key == "SharedInfo":
            current["SharedInfo"] = value
        elif key == "key_data":
            rows.append((current["Z"], current["SharedInfo"], value))
    return rows


def hkdf():
    rows, current = [], {}
    for line in show("rfc-5869-HKDF-SHA256.txt").splitlines():
        key, sep, value = line.partition("=")
        if not sep:
            continue
        key, value = key.strip(), value.strip()
        if key == "COUNT":
            current = {}
        current[key] = value
        if key == "OKM":
            rows.append((current["IKM"], current["salt"], current["info"], current["L"],
                         current["PRK"], current["OKM"]))
    return rows


print("// Generated by vectors.py from swift-crypto", revision, "Tests/Test Vectors. Do not edit.")
emit("wycheproofECDSADER", ecdsa("ecdsa_secp256r1_sha256_test.json"))
emit("wycheproofECDSAP1363", ecdsa("ecdsa_secp256r1_sha256_p1363_test.json"))
emit("wycheproofECDHPoint", ecdh("ecdh_secp256r1_ecpoint_test.json", True))
emit("wycheproofECDHSPKI", ecdh("ecdh_secp256r1_test.json", False))
emit("cavsX963SHA256", x963())
emit("rfc5869SHA256", hkdf())
